#!/usr/bin/env python3
"""Generate PARTS_CATALOG.md: every part in the parts list with size, hole pattern, usage and notes.
Hole data comes from the official LDraw primitives (pin holes vs axle holes, and their directions)."""
import sys,os,re,collections
sys.path.insert(0,os.path.dirname(__file__)); import numpy as np
from ldflat import find, flatten
from ldcheck import geom_vertices, parse_model, flatten_model
HOLE=re.compile(r'^(beamhol|connhol|npeghol|peghole|axlehol\d|axl\dhol|axlehole|axleho\d|connhole)',re.I)
AXL=re.compile(r'^(axlehol\d|axl\dhol|axlehole|axleho\d)',re.I)
import functools
@functools.lru_cache(None)
def _tris(ref):
    os.environ.setdefault('LDGEOM','official')
    sys.argv=sys.argv[:1]
    from ldrender import tris
    T=[v for c,v in tris(ref)]
    return np.array(T) if T else np.zeros((0,3,3))
def _hits(T,o,d):
    """Moller-Trumbore: does the infinite line o + t*d hit any triangle?"""
    v0,v1,v2=T[:,0],T[:,1],T[:,2]; e1=v1-v0; e2=v2-v0
    h=np.cross(d,e2); a=(e1*h).sum(1); ok=np.abs(a)>1e-9
    f=np.zeros_like(a); f[ok]=1/a[ok]; s_=o-v0; u=f*(s_*h).sum(1); q=np.cross(s_,e1); v=f*(q@d)
    return bool((ok&(u>=0)&(u<=1)&(v>=0)&(u+v<=1)).any())
def holes(ref):
    """Physical through-hole test on the 20-LDU grid: the axis ray passes clean through the part,
    while rays 7.5 LDU to each side hit material. Type from the nearest LDraw hole primitive (axle vs pin)."""
    T=_tris(ref)
    if not len(T): return collections.Counter()
    lo,hi=T.reshape(-1,3).min(0),T.reshape(-1,3).max(0)
    prims=[(b,P) for b,M,P in flatten(ref,keep=HOLE)]
    c=collections.Counter()
    for d in range(3):
        D=np.zeros(3); D[d]=1; a,b=[i for i in range(3) if i!=d]
        best=None
        for oa in (0,10):
            for ob in (0,10):
                found=[]
                for x in np.arange(np.floor((lo[a]-oa)/20)*20+oa, hi[a]+1, 20):
                    for y in np.arange(np.floor((lo[b]-ob)/20)*20+ob, hi[b]+1, 20):
                        o=np.zeros(3); o[a]=x; o[b]=y
                        if _hits(T,o,D): continue
                        side=0
                        for dx,dy in ((7.5,0),(-7.5,0),(0,7.5),(0,-7.5)):
                            o2=o.copy(); o2[a]+=dx; o2[b]+=dy; side+=_hits(T,o2,D)
                        if side>=3: found.append(o)
                if best is None or len(found)>len(best): best=found
        for o in best:
            near=[n for n,P in prims if abs(P[a]-o[a])<6 and abs(P[b]-o[b])<6]
            t='axle' if any(AXL.match(n) for n in near) else 'pin'
            c[(('X','Y','Z')[d],t)]+=1
    return c
def builtin_pins(ref): return sum(1 for _ in flatten(ref,keep=re.compile(r'^connect|^confric',re.I)))
def size(ref):
    v=np.array(geom_vertices(ref)); 
    if not len(v): return '?'
    e=np.sort(np.ptp(v,axis=0))[::-1]/20; return '×'.join(f'{x:g}' for x in np.round(e*2)/2)
def desc(ref):
    p=find(ref); 
    if not p: return 'NOT IN LIBRARY'
    d=open(p,errors='replace').readline()[2:].strip()
    if d.startswith('~Moved to'):
        tgt=d.split()[-1]+'.dat'; q=find(tgt); d=(open(q,errors='replace').readline()[2:].strip() if q else d)+f' (={tgt[:-4]})'
    return d.replace('|','/')
# usage counts across the models in designs/
from config import DESIGNS, REPO, CATALOG_OUT, PARTS
import glob
use=collections.Counter()
for f in sorted(glob.glob(os.path.join(DESIGNS,'**','*.ldr'),recursive=True)+glob.glob(os.path.join(DESIGNS,'**','*.mpd'),recursive=True)):
    if os.path.exists(f):
        m,o=parse_model(f)
        for p in flatten_model(m,o,f): use[p['ref'].replace('.dat','')]+=1
from catalog_data import NOTES
from partslist import load as _load_parts, EQUIV, canonical
_items=_load_parts()
LISTED=set()
for it in _items:
    LISTED|={it['pid'],it.get('equiv')}-{None}
def row(pn,note):
    ref=pn+'.dat'
    if not find(ref): return f'| {pn} | not in library | | | | {use.get(pn,"") or ""} | {note} |'
    h=holes(ref); hs=' '.join(f"{n}{'P' if t=='pin' else 'A'}{ax}" for (ax,t),n in sorted(h.items())) or '—'
    bp=builtin_pins(ref)
    return f'| {pn} | {desc(ref)[:60]} | {size(ref)} | {hs} | {bp or ""} | {use.get(pn,"") or ""} | {note} |'
HDR=['| Part | Description | Size | Holes | Built-in | Used | Notes |','|---|---|---|---|---|---|---|']
groups={}
for it in _items:
    if it['pid']: groups.setdefault(it['category'],[]).append(it['pid'])
unlisted=sorted(p for p in use if find(p+'.dat') and p not in LISTED and canonical(p) not in LISTED
                and not p.lower().startswith(('s/','48/','8/')))
rel=os.path.relpath(PARTS,REPO) if PARTS.startswith(REPO) else os.path.basename(PARTS)
out=['# FLL Parts Catalog','',
 f'Every part in the parts list (`{rel}`): what it is, its size, its holes, and when we use it.',
 'The parts list is the set of parts available to design with. Generated by `tools/catalog.py` from the',
 'LDraw library; notes live in `tools/catalog_data.py`.','',
 '**Columns.** *Size*: bounding box in studs (largest first). *Holes*: **through-holes** found by looking',
 'through the part (ray test), pin **P** or axle **A**, per direction in the part\'s own frame (X/Y/Z).',
 'Alternating-hole liftarms show two directions. Blind holes (motors, hub) are under-counted; see',
 'DESIGN_RULES §4 for those. Small cross blocks and frames: verify in Stud.io. *Built-in*: pins molded onto the part. *Used*: count across',
 'the models in `designs/` (yours; git-ignored). **★ = preferred**, **✗ = avoid unless nothing else fits.**','',
 'Design with listed parts only; anything else must be called out as "needs ordering".','']
for g,pns in groups.items():
    out+=[f'## {g}','']+HDR+[row(pn,NOTES.get(pn,'')) for pn in pns]+['']
if unlisted:
    out+=['## Used in your designs but not in the parts list','','Add these to the parts list if you own them; otherwise don\'t design with them.','']+HDR
    out+=[row(pn,'') for pn in unlisted]+['']
open(CATALOG_OUT,'w').write('\n'.join(out)+'\n')
print('wrote',CATALOG_OUT, sum(len(v) for v in groups.values()),'listed parts', f'+ {len(unlisted)} used but unlisted' if unlisted else '')
